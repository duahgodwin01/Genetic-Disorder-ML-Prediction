# ============================================================
# STEP 2: PREPROCESSING
# ============================================================

from sklearn.preprocessing import LabelEncoder
from sklearn.impute import SimpleImputer

# --- 2A: Drop useless columns ---
drop_cols = [
    'Patient Id', 'Patient First Name', 'Family Name',
    "Father's name", 'Institute Name', 'Location of Institute'
]
train = train.drop(columns=drop_cols)
test = test.drop(columns=drop_cols)

print("After dropping useless columns:")
print("Train shape:", train.shape)
print("Test shape:", test.shape)

# --- 2B: Separate targets from features ---
target_primary = 'Genetic Disorder'
target_secondary = 'Disorder Subclass'

y_primary = train[target_primary]
y_secondary = train[target_secondary]

X_train = train.drop(columns=[target_primary, target_secondary])
X_test = test.copy()

print("\nFeatures shape:", X_train.shape)
print("Primary target distribution:")
print(y_primary.value_counts())

# --- 2C: Encode categorical columns ---
cat_cols = X_train.select_dtypes(include='object').columns.tolist()
print("\nCategorical columns to encode:", cat_cols)

le = LabelEncoder()
for col in cat_cols:
    # Combine train and test to ensure consistent encoding
    combined = pd.concat([X_train[col], X_test[col]], axis=0).astype(str)
    le.fit(combined)
    X_train[col] = le.transform(X_train[col].astype(str))
    X_test[col] = le.transform(X_test[col].astype(str))

print("\nAfter encoding - Train dtypes:")
print(X_train.dtypes.value_counts())

# --- 2D: Impute missing values ---
imputer = SimpleImputer(strategy='median')
X_train_imputed = pd.DataFrame(
    imputer.fit_transform(X_train),
    columns=X_train.columns
)
X_test_imputed = pd.DataFrame(
    imputer.transform(X_test),
    columns=X_test.columns
)

print("\nMissing values after imputation:")
print("Train:", X_train_imputed.isnull().sum().sum())
print("Test:", X_test_imputed.isnull().sum().sum())

# --- 2E: Encode target variables ---
le_primary = LabelEncoder()
le_secondary = LabelEncoder()

y_primary_encoded = le_primary.fit_transform(y_primary.astype(str))
y_secondary_encoded = le_secondary.fit_transform(y_secondary.astype(str))

print("\nPrimary target classes:", le_primary.classes_)
print("Secondary target classes:", le_secondary.classes_)


# ============================================================
# STEP 2F: REMOVE ROWS WITH MISSING TARGET VALUES
# ============================================================

# Combine features and targets temporarily
train_clean = X_train_imputed.copy()
train_clean['target_primary'] = y_primary.values
train_clean['target_secondary'] = y_secondary.values

# Remove rows where either target is missing
train_clean = train_clean.dropna(subset=['target_primary', 'target_secondary'])

print("Rows before cleaning:", X_train_imputed.shape[0])
print("Rows after cleaning:", train_clean.shape[0])
print("Rows removed:", X_train_imputed.shape[0] - train_clean.shape[0])

# Separate back into features and targets
X_train_clean = train_clean.drop(columns=['target_primary', 'target_secondary'])
y_primary_clean = train_clean['target_primary']
y_secondary_clean = train_clean['target_secondary']

# Re-encode targets without nan
