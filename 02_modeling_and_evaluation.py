# STEP 12: EXPANDED EVALUATION METRICS
# Addressing the limitations of weighted F1 on imbalanced data
# ============================================================

from sklearn.metrics import (f1_score, balanced_accuracy_score,
                             recall_score, precision_score, accuracy_score)

models = {
    'Logistic Regression': y_pred_lr_primary,
    'Random Forest': y_pred_rf_primary,
    'XGBoost': y_pred_xgb_primary
}

# --- Aggregate metrics comparison ---
rows = []
for name, preds in models.items():
    rows.append({
        'Model': name,
        'Accuracy': accuracy_score(y_val_primary, preds),
        'Weighted F1': f1_score(y_val_primary, preds, average='weighted'),
        'Macro F1': f1_score(y_val_primary, preds, average='macro'),
        'Balanced Accuracy': balanced_accuracy_score(y_val_primary, preds)
    })

agg_df = pd.DataFrame(rows).round(4)

print("=" * 75)
print("AGGREGATE METRICS — PRIMARY TARGET")
print("=" * 75)
print(agg_df.to_string(index=False))
print("\nNote: Random baseline for 3 classes = 0.3333 balanced accuracy")

# --- Per-class recall (the clinically important view) ---
print("\n" + "=" * 75)
print("PER-CLASS RECALL — proportion of each disorder correctly identified")
print("=" * 75)

recall_rows = []
for name, preds in models.items():
    r = recall_score(y_val_primary, preds, average=None)
    recall_rows.append({
        'Model': name,
        'Mitochondrial': r[0],
        'Multifactorial': r[1],
        'Single-Gene': r[2]
    })

recall_df = pd.DataFrame(recall_rows).round(4)
print(recall_df.to_string(index=False))

# --- Per-class F1 ---
print("\n" + "=" * 75)
print("PER-CLASS F1 SCORES")
print("=" * 75)

f1_rows = []
for name, preds in models.items():
    f = f1_score(y_val_primary, preds, average=None)
    f1_rows.append({
        'Model': name,
        'Mitochondrial': f[0],
        'Multifactorial': f[1],
        'Single-Gene': f[2]
    })

f1_df = pd.DataFrame(f1_rows).round(4)
print(f1_df.to_string(index=False))

# --- The weighted vs macro gap ---
