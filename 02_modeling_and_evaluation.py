from sklearn.metrics import roc_auc_score, roc_curve, auc
from sklearn.preprocessing import label_binarize

# --- Binarize the true labels for OvR computation ---
y_val_bin = label_binarize(y_val_primary, classes=[0, 1, 2])
class_labels = ['Mitochondrial', 'Multifactorial', 'Single-Gene']

# --- Get predicted probabilities from each model ---
proba = {
    'Logistic Regression': lr_primary.predict_proba(X_val_primary),
    'Random Forest':       rf_primary.predict_proba(X_val_primary),
    'XGBoost':             xgb_primary.predict_proba(X_val_primary)
}

# --- Aggregate OvR AUC (macro and weighted) ---
print("=" * 70)
print("ROC-AUC (ONE-VS-REST) — PRIMARY TARGET")
print("=" * 70)
print("Random baseline AUC = 0.5000\n")

auc_rows = []
for name, p in proba.items():
    macro = roc_auc_score(y_val_primary, p, multi_class='ovr', average='macro')
    weighted = roc_auc_score(y_val_primary, p, multi_class='ovr', average='weighted')
    auc_rows.append({'Model': name, 'Macro AUC': macro, 'Weighted AUC': weighted})

auc_df = pd.DataFrame(auc_rows).round(4)
print(auc_df.to_string(index=False))

# --- Per-class AUC ---
print("\n" + "=" * 70)
print("PER-CLASS AUC (One-vs-Rest)")
print("=" * 70)

perclass_rows = []
for name, p in proba.items():
    row = {'Model': name}
    for i, cls in enumerate(class_labels):
        row[cls] = roc_auc_score(y_val_bin[:, i], p[:, i])
    perclass_rows.append(row)

perclass_auc_df = pd.DataFrame(perclass_rows).round(4)
print(perclass_auc_df.to_string(index=False))


